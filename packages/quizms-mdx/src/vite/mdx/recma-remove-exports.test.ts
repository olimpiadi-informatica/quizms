import { describe, expect, it } from "vitest";

import recmaRemoveExports from "./recma-remove-exports";
import remarkImages from "./remark-images";
import { compileMdx } from "./test-utils";

describe("recmaRemoveExports", () => {
  it("turns exported declarations into local declarations", async () => {
    const code = await compileMdx(
      `
export const a = 1, b = 2;
export function f() {}
export class C {}

{a + b}
`,
      { recmaPlugins: [recmaRemoveExports] },
    );
    expect(code).toContain("\nconst a = 1, b = 2;\nfunction f() {}\nclass C {}\n");
    expect(code).not.toMatch(/export (const|function|class)/);
  });

  it("keeps the default export and export lists", async () => {
    const code = await compileMdx("export const a = 1;\nexport { a as b };\n\n{a}", {
      recmaPlugins: [recmaRemoveExports],
    });
    expect(code).toContain("export {a as b};");
    expect(code).toContain("export default function MDXContent");
  });

  it("removes the exports generated by the pipeline", async () => {
    // `remark-images` exports the globs of the images with variables.
    const source = "![x](img/{x}.png)\n\nexport const x = 1;";
    const withExports = await compileMdx(source, { remarkPlugins: [remarkImages] });
    const withoutExports = await compileMdx(source, {
      remarkPlugins: [remarkImages],
      recmaPlugins: [recmaRemoveExports],
    });
    expect(withExports).toContain("export const __img__0__");
    expect(withoutExports).toContain("\nconst __img__0__");
    expect(withoutExports).not.toContain("export const");
  });
});
